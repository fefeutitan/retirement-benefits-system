CREATE TABLE documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beneficio_id BIGINT NOT NULL,
    nome_arquivo VARCHAR(255) NOT NULL,
    tipo_mime VARCHAR(100) NOT NULL,
    tamanho BIGINT NOT NULL,
    categoria VARCHAR(40) NOT NULL,
    conteudo BYTEA NOT NULL,
    anexado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_documento_beneficio FOREIGN KEY (beneficio_id) REFERENCES beneficio(id)
);

CREATE TABLE tramitacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beneficio_id BIGINT NOT NULL,
    setor_origem VARCHAR(120) NOT NULL,
    setor_destino VARCHAR(120) NOT NULL,
    responsavel VARCHAR(150) NOT NULL,
    observacao VARCHAR(500),
    tramitado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_tramitacao_beneficio FOREIGN KEY (beneficio_id) REFERENCES beneficio(id)
);
